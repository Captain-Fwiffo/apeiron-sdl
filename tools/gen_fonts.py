"""Renders the glyph tables of src/fontdata.c from open-licence fonts (SIL Open Font License: Noto Serif, Liberation Sans).
Run:  python tools/gen_fonts.py > src/fontdata.c      (the fonts are looked up in C:\Windows\Fonts or the folders given in FONT_DIRS)
Each table holds ASCII 32..126: advance, bitmap size, offset from the pen (x) and the baseline (y), 8-bit coverage."""
import os, sys
from PIL import ImageFont, ImageDraw, Image

DIRS = [r'C:\Windows\Fonts', '/usr/share/fonts/truetype/noto', '/usr/share/fonts/truetype/liberation', '/usr/share/fonts/TTF'] + os.environ.get('FONT_DIRS', '').split(os.pathsep)
SPECS = [('serif18', 'NotoSerif-Regular.ttf', 18), ('sans9', 'LiberationSans-Regular.ttf', 9), ('sans9b', 'LiberationSans-Bold.ttf', 9)]

def find(name):
    for d in DIRS:
        p = os.path.join(d, name)
        if d and os.path.exists(p):
            return p
    sys.exit('font not found: ' + name)

out = ['/* Generated by tools/gen_fonts.py from Noto Serif and Liberation Sans (SIL Open Font License 1.1). Do not edit. */',
       '#include "fontdata.h"', '']
for ident, fname, px in SPECS:
    font = ImageFont.truetype(find(fname), px, layout_engine=ImageFont.Layout.BASIC)
    asc, desc = font.getmetrics()
    glyphs = []
    blob = []
    off = 0
    for c in list(range(32, 127)) + [0xA9]:
        ch = chr(c)
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch, anchor='ls')           # relative to the pen on the baseline
        w, h = max(0, r - l), max(0, b - t)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor='ls')
            data = list(im.getdata())
        else:
            data = []
        glyphs.append((adv, w, h, l, t, off))
        blob += data
        off += len(data)
    out.append('static const unsigned char %s_px[] = {' % ident)
    for i in range(0, len(blob), 24):
        out.append('    ' + ','.join(str(v) for v in blob[i:i + 24]) + ',')
    out.append('    0 };')
    out.append('static const FGlyph %s_gl[96] = {' % ident)
    for g in glyphs:
        out.append('    { %d, %d, %d, %d, %d, %d },' % g)
    out.append('};')
    out.append('const FFont font_%s = { %d, %s_gl, %s_px };' % (ident, asc, ident, ident))
    out.append('')
print('\n'.join(out))
