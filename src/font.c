int font_width(int scale, const char *s) { return (int)strlen(s) * 6 * scale; }

int font_draw(uint32_t *img, int img_w, int img_h, int x, int y, int scale, uint32_t color, const char *s)
{
    int x0 = x;
    for (; *s; s++, x += 6 * scale) {
        unsigned c = (unsigned char)*s;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *gl = kFont[c - 32];
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 8; row++) {
                if (!(gl[col] >> row & 1)) continue;
                for (int dy = 0; dy < scale; dy++)
                    for (int dx = 0; dx < scale; dx++) {
                        int px = x + col * scale + dx, py = y + row * scale + dy;
                        if (px >= 0 && px < img_w && py >= 0 && py < img_h) img[py * img_w + px] = color;
                    }
            }
    }
    return x - x0;
}

/* the same glyphs, spaced by their own width (the pages of the instructions have long lines) */
static int glyph_cols(const uint8_t *gl, int *first)
{
    int a = 5, b = -1;
    for (int c = 0; c < 5; c++) if (gl[c]) { if (c < a) a = c; b = c; }
    if (b < 0) { *first = 0; return 0; }
    *first = a;
    return b - a + 1;
}

int font_width_p(int scale, const char *s)
{
    int w = 0;
    for (; *s; s++) {
        unsigned c = (unsigned char)*s;
        if (c < 32 || c > 126) c = '?';
        int first, n = glyph_cols(kFont[c - 32], &first);
        w += (n ? n + 1 : 3) * scale;
    }
    return w;
}

int font_draw_p(uint32_t *img, int img_w, int img_h, int x, int y, int scale, uint32_t color, const char *s)
{
    int x0 = x;
    for (; *s; s++) {
        unsigned c = (unsigned char)*s;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *gl = kFont[c - 32];
        int first, n = glyph_cols(gl, &first);
        for (int col = 0; col < n; col++)
            for (int row = 0; row < 8; row++) {
                if (!(gl[first + col] >> row & 1)) continue;
                for (int dy = 0; dy < scale; dy++)
                    for (int dx = 0; dx < scale; dx++) {
                        int px = x + col * scale + dx, py = y + row * scale + dy;
                        if (px >= 0 && px < img_w && py >= 0 && py < img_h) img[py * img_w + px] = color;
                    }
            }
        x += (n ? n + 1 : 3) * scale;
    }
    return x - x0;
}

/* ---- text from the rendered glyph tables ---- */
static const FGlyph *ffont_glyph(const FFont *f, unsigned char c)
{
    if (c == 0xA9) return &f->gl[95];
    if (c < 32 || c > 126) c = '?';
    return &f->gl[c - 32];
}

int ffont_width(const FFont *f, const char *s)
{
    int w = 0;
    for (; *s; s++) w += ffont_glyph(f, (unsigned char)*s)->advance;
    return w;
}

int ffont_draw(uint32_t *img, int img_w, int img_h, int x, int baseline, const FFont *f, uint32_t color, const char *s)
{
    int x0 = x;
    unsigned cr = (color >> 16) & 255u, cg = (color >> 8) & 255u, cb = color & 255u;
    for (; *s; s++) {
        const FGlyph *g = ffont_glyph(f, (unsigned char)*s);
        for (int row = 0; row < g->h; row++)
            for (int col = 0; col < g->w; col++) {
                unsigned a = f->px[g->off + row * g->w + col];
                int px = x + g->x + col, py = baseline + g->y + row;
                if (!a || px < 0 || px >= img_w || py < 0 || py >= img_h) continue;
                uint32_t d = img[py * img_w + px];
                unsigned r = (((d >> 16) & 255u) * (255 - a) + cr * a) / 255u, gg = (((d >> 8) & 255u) * (255 - a) + cg * a) / 255u, b = ((d & 255u) * (255 - a) + cb * a) / 255u;
                img[py * img_w + px] = 0xFF000000u | r << 16 | gg << 8 | b;
            }
        x += g->advance;
    }
    return x - x0;
}
